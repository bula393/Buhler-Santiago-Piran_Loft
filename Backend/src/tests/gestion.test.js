import test from "node:test";
import assert from "node:assert/strict";
import app from "../app.js";

test("Gestión completa, relaciones, saldo y reservas sin superposición", async (t) => {
    const server = app.listen(0, "127.0.0.1");
    await new Promise((resolve) => server.once("listening", resolve));
    t.after(() => new Promise((resolve) => server.close(resolve)));
    const base = `http://127.0.0.1:${server.address().port}/api`;
    async function api(ruta, method = "GET", body, esperado = 200) {
        const respuesta = await fetch(`${base}/${ruta}`, { method,
            ...(body ? { headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) } : {}) });
        const json = await respuesta.json();
        assert.equal(respuesta.status, esperado, `${method} ${ruta}: ${JSON.stringify(json)}`);
        assert.equal(json.success, esperado < 400);
        return json.data;
    }
    const unidad = await api("unidades", "POST", { nombre: "Loft QA", descripcion: "Prueba", capacidad: 2,
        direccion: "Dirección de prueba", disponible: true, latitud: -34.6037, longitud: -58.3816 }, 201);
    assert.equal(unidad.latitud, -34.6037);
    await api(`unidades/${unidad.id}`, "PUT", { latitud: 95 }, 400);
    const huesped = await api("huespedes", "POST", { nombre: "Huésped QA", email: "qa@example.com", telefono: "123456", documento: "QA-1" }, 201);
    await api("huespedes", "POST", { nombre: "Otro", email: "QA@example.com", telefono: "1", documento: "QA-2" }, 400);
    await api("huespedes", "POST", { nombre: "Otro", email: "incorrecto", telefono: "1", documento: "QA-3" }, 400);
    const datosReserva = { huespedId: huesped.id, unidadId: unidad.id, fechaInicio: "2020-01-10", fechaFin: "2020-01-12", estado: "confirmada", cantidadHuespedes: 2, montoTotal: 1000 };
    const reserva = await api("reservas", "POST", datosReserva, 201);
    await api("reservas", "POST", { ...datosReserva, fechaInicio: "2020-01-11" }, 400);
    await api("reservas", "POST", { ...datosReserva, fechaInicio: "2020-02-30", fechaFin: "2020-03-02" }, 400);
    await api("reservas", "POST", { ...datosReserva, fechaInicio: "2020-01-20", fechaFin: "2020-01-22", cantidadHuespedes: 3 }, 400);
    await api("reservas", "POST", { ...datosReserva, huespedId: 999 }, 400);
    const adyacente = await api("reservas", "POST", { ...datosReserva, fechaInicio: "2020-01-12", fechaFin: "2020-01-14" }, 201);
    await api(`unidades/${unidad.id}`, "PUT", { capacidad: 1 }, 400);
    await api(`unidades/${unidad.id}`, "DELETE", undefined, 400);
    await api(`huespedes/${huesped.id}`, "DELETE", undefined, 400);
    const datosPago = { reservaId: reserva.id, monto: 600.25, fecha: "2020-01-10", metodoPago: "tarjeta_simulada", estado: "aprobado" };
    const pago = await api("pagos", "POST", datosPago, 201);
    await api("pagos", "POST", { ...datosPago, monto: 400 }, 400);
    await api("pagos", "POST", { ...datosPago, monto: 1.001 }, 400);
    await api(`pagos/${pago.id}`, "PUT", { reservaId: adyacente.id }, 400);
    await api(`reservas/${reserva.id}`, "PUT", { montoTotal: 500 }, 400);
    await api(`reservas/${reserva.id}`, "PUT", { estado: "cancelada" }, 400);
    const segundoPago = await api("pagos", "POST", { ...datosPago, monto: 399.75 }, 201);
    const pagos = await api("pagos");
    assert.equal(pagos.filter((p) => p.reservaId === reserva.id).reduce((total, p) => total + Math.round(p.monto * 100), 0), 100000);
    const datosResena = { reservaId: reserva.id, puntaje: 5, comentario: "Excelente estadía de prueba", fecha: "2020-01-12" };
    await api("resenas", "POST", datosResena, 400);
    await api(`reservas/${reserva.id}`, "PUT", { estado: "finalizada" });
    const resena = await api("resenas", "POST", datosResena, 201);
    await api("resenas", "POST", datosResena, 400);
    await api(`resenas/${resena.id}`, "PUT", { puntaje: 6 }, 400);
    await api(`reservas/${reserva.id}`, "PUT", { estado: "confirmada" }, 400);
    await api(`reservas/${reserva.id}`, "PUT", { fechaFin: "2020-01-11" }, 400);
    await api(`reservas/${reserva.id}`, "DELETE", undefined, 400);
    await api(`resenas/${resena.id}`, "PUT", { puntaje: 4 });
    assert.equal((await api(`resenas/${resena.id}`)).puntaje, 4);
    await api(`resenas/${resena.id}`, "DELETE");
    await api(`pagos/${pago.id}`, "PUT", { estado: "anulado" });
    await api(`pagos/${segundoPago.id}`, "DELETE");
    await api(`reservas/${reserva.id}`, "PUT", { estado: "cancelada" });
    await api(`pagos/${pago.id}`, "PUT", { estado: "aprobado" }, 400);
    await api(`pagos/${pago.id}`, "DELETE");
    await api(`reservas/${reserva.id}`, "DELETE");
    await api(`reservas/${adyacente.id}`, "DELETE");
    const checkout = { ...datosReserva, fechaInicio: "2020-03-01", fechaFin: "2020-03-03", metodoPago: "transferencia_simulada" };
    await api("reservas/con-pago", "POST", { ...checkout, metodoPago: "invalido" }, 400);
    assert.deepEqual(await api("reservas"), []);
    assert.deepEqual(await api("pagos"), []);
    const conjunta = await api("reservas/con-pago", "POST", checkout, 201);
    assert.equal(conjunta.pago.reservaId, conjunta.reserva.id);
    assert.equal(conjunta.pago.monto, conjunta.reserva.montoTotal);
    assert.equal(conjunta.pago.estado, "aprobado");
    await api("reservas/con-pago", "POST", checkout, 400);
    assert.equal((await api("reservas")).length, 1);
    assert.equal((await api("pagos")).length, 1);
    await api(`pagos/${conjunta.pago.id}`, "DELETE");
    await api(`reservas/${conjunta.reserva.id}`, "DELETE");
    await api(`huespedes/${huesped.id}`, "PUT", { telefono: "654321" });
    await api(`huespedes/${huesped.id}`, "DELETE");
    await api(`unidades/${unidad.id}`, "DELETE");
    await api(`reservas/${reserva.id}`, "GET", undefined, 404);
    for (const recurso of ["unidades", "huespedes", "reservas", "pagos", "resenas"]) assert.deepEqual(await api(recurso), []);
});
